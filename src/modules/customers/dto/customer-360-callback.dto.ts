import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import {
  IsArray,
  IsEnum,
  IsNotEmpty,
  IsOptional,
  IsString,
  IsUUID,
} from 'class-validator';

export enum Customer360Status {
  SUCCESS = 'SUCCESS',
  FAILED = 'FAILED',
}

export class Customer360CallbackDto {
  @ApiProperty({ description: 'UUID of the customer being analyzed' })
  @IsUUID()
  @IsNotEmpty()
  customerId!: string;

  @ApiProperty({ description: 'WorkflowRun UUID correlated to this execution' })
  @IsUUID()
  @IsNotEmpty()
  workflowRunId!: string;

  @ApiProperty({ enum: Customer360Status, example: 'SUCCESS' })
  @IsEnum(Customer360Status)
  status!: Customer360Status;

  @ApiPropertyOptional({
    description: 'Executive summary generated by Gemini AI',
  })
  @IsOptional()
  @IsString()
  summary?: string;

  @ApiPropertyOptional({
    type: [String],
    description: 'Identified customer strengths',
  })
  @IsOptional()
  @IsArray()
  keyStrengths?: string[];

  @ApiPropertyOptional({
    type: [String],
    description: 'Identified customer risks or churn signals',
  })
  @IsOptional()
  @IsArray()
  potentialRisks?: string[];

  @ApiPropertyOptional({
    type: [String],
    description: 'Identified upsell or expansion opportunities',
  })
  @IsOptional()
  @IsArray()
  growthOpportunities?: string[];

  @ApiPropertyOptional({
    description: 'Recommended next action for sales or customer success',
  })
  @IsOptional()
  @IsString()
  recommendedNextAction?: string;

  @ApiPropertyOptional({ description: 'Source coverage indicators' })
  @IsOptional()
  sourceCoverage?: Record<string, string>;

  @ApiPropertyOptional({ description: 'Raw LLM response payload' })
  @IsOptional()
  rawAIOutput?: Record<string, any>;

  @ApiPropertyOptional({ description: 'Error message if analysis failed' })
  @IsOptional()
  @IsString()
  errorMessage?: string;
}

export class Customer360CallbackResponseDto {
  @ApiProperty({ example: true })
  success!: boolean;

  @ApiProperty({ example: '5dbc025e-1185-4977-8db5-046924340739' })
  customerId!: string;

  @ApiProperty({ example: '9a8b7c6d-5e4f-3a2b-1c0d-e9f8a7b6c5d4' })
  workflowRunId!: string;
}
